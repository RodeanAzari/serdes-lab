#!/usr/bin/env bash
# Reference vectors for model/prng.py from L'Ecuyer's lfsr258.c (not committed: no license given).
# Usage: scripts/lfsr258_ref.sh <path/to/lfsr258.c>  ->  model/tests/data/lfsr258_ref.txt
# Source: http://simul.iro.umontreal.ca/rng/lfsr258.c (SHA-256 checked below).
set -euo pipefail
SRC=$(realpath "$1")
SHA=4cceaf692afb49d6fe02c99282cd92438d3966529b8091c715fa15c0a7462ef4  # downloaded 2026-11-08
OUT=$(realpath "$(dirname "$0")/..")/model/tests/data/lfsr258_ref.txt
GOT=$(sha256sum "$SRC" | cut -d' ' -f1)
[ "$GOT" = "$SHA" ] || { echo "sha256 mismatch: got $GOT, pinned $SHA" >&2; exit 1; }
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
echo 'double lfsr258(void);' > "$W/lfsr258.h"
cp "$SRC" "$W/lfsr258.c"
cat > "$W/harness.c" <<'EOF'
#include <stdio.h>
#include <stdlib.h>
#include "lfsr258.c"
/* argv: n_first last_step y1..y5 (hex). Prints words 0..n_first-1 and word last_step-1. */
int main(int argc, char **argv) {
  if (argc != 8) return 2;
  long n = atol(argv[1]), last = atol(argv[2]);
  y1 = strtoull(argv[3], 0, 16); y2 = strtoull(argv[4], 0, 16); y3 = strtoull(argv[5], 0, 16);
  y4 = strtoull(argv[6], 0, 16); y5 = strtoull(argv[7], 0, 16);
  for (long i = 0; i < last; i++) {
    lfsr258();
    if (i < n || i == last - 1) printf("%ld %016llx\n", i, (unsigned long long)(y1 ^ y2 ^ y3 ^ y4 ^ y5));
  }
  return 0;
}
EOF
gcc -O2 -Wall -Wno-unused-parameter -o "$W/harness" "$W/harness.c"
mkdir -p "$(dirname "$OUT")"
{
  echo "# lfsr258 reference vectors: <step> <word> after each 'seed y1..y5' line (hex)."
  echo "# Generated by scripts/lfsr258_ref.sh from http://simul.iro.umontreal.ca/rng/lfsr258.c"
  echo "# source sha256 $GOT ; $(gcc --version | head -1) ; $(date -u +%F)"
  # Seeds: the reference default (GERME), the minimum legal seed, model.prng.lane_seeds(2026, 2)
  while read -r s; do
    echo "seed $s"
    # shellcheck disable=SC2086
    "$W/harness" 64 20000 $s
  done <<'SEEDS'
1b69b4bacd05f15 1b69b4bacd05f15 1b69b4bacd05f15 1b69b4bacd05f15 1b69b4bacd05f15
2 200 1000 20000 800000
db9c559891948d23 f8bc927ded35455d aad71e75cde2b88e e280938ad5a104f2 caa69c1e0798ff49
b9f5a07176645a03 f3f8751c656739ae cdf6c4e563d8e22d d5b871711a2012f4 bae578fd14e84742
SEEDS
} > "$OUT"
echo "wrote $OUT (source sha256 $GOT)"
